/**
 * 一次代理执行的来源。
 *
 * 它不改变执行链本身——诊断探测、工作流的模型节点与真实请求走的是同一条路（同样的
 * 规划、重试、协议转换、健康度写入）。它只回答一个问题：**这次执行是不是「代理替客户端
 * 处理的一次请求」**。
 *
 * 需要这个区别的地方是产品统计（`telemetry.md` §5.3）：`request_completed` 数的是
 * 「这台机器替客户端处理了多少任务」，而连接测试、能力自检、工作流里的模型调用都是产品
 * 自己发起的中间步骤——它们各自的用量由自己的事件回答（`provider_tested` /
 * `workflow_node_executed`），再计一次任务数就会把一次任务数成两次以上。
 *
 * 因此它是**必填**的：新增一个调用方时必须在类型上表明自己属于哪一侧，没有默认值可继承。
 */
export type ExecutionOrigin = 'client' | 'internal'
