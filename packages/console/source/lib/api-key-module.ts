/**
 * 「客户端 API Key 模块开着吗」的唯一判定。
 *
 * 这个开关被五处消费：侧边栏入口、Key 管理页、统计页的按 Key 用量、请求日志的 Key 筛选、
 * 活跃度查询的轮询。每处自己写一遍 `?? true` / `!x` 就会写出两套口径——历史上正是如此：
 * 侧边栏按「没读到就算开着」显示入口，管理页按「没读到就算关着」把用户弹回统计页，
 * 于是点进去只看到页面闪一下又退出来。
 *
 * 所以判定只在这里做，而且**只有显式的 `false` 算关**：
 *
 * - 设置还没加载出来（`undefined` / `null`）：按开着算。先少一个入口再冒出来，比先给一个
 *   点进去是空页的入口更难受。
 * - 老版本服务端不认识这个字段时同样回 `undefined`：按开着算，才不会把升级过程中的
 *   一次读设置变成「整块功能消失」。
 */
export function isApiKeyModuleEnabled(flag: boolean | null | undefined): boolean {
  return flag !== false
}
