  add('| Token | 亮色 | 暗色 | 允许 | 不得 | 阈值 |')
  add('| --- | --- | --- | --- | --- | --- |')
  for (const [name, role] of Object.entries(data.roles.light)) {
    add(`| \`${name}\` | ${role.hex} | ${data.roles.dark[name].hex} | ${esc(role.allowed)} | ${esc(role.forbidden)} | ${esc(role.threshold)} |`)
  }
  add('')
  add('## 3. P0 / P1 修复前后')
  add('')
  add('| ID | 级别 | 问题 | 修改前 | v2 | 阈值 | 处置 |')
  add('| --- | --- | --- | --- | --- | --- | --- |')
  for (const issue of data.issues.filter(item => item.severity === 'P0' || item.severity === 'P1')) {
    add(`| ${issue.id} | ${issue.severity} | ${esc(issue.title)} | ${esc(issue.before)} | ${esc(issue.after)} | ${esc(issue.target)} | ${verdictLabel(issue.verdict)} |`)
  }
  add('')
  add('## 4. 对比度矩阵')
  add('')
  add('| 用途 | 前景 | 承载底色 | 亮色 | 暗色 | 阈值 |')
  add('| --- | --- | --- | --- | --- | --- |')
  for (const pair of data.pairs) {
    const light = data.contrast.light.find(item => item.id === pair.id)
    const dark = data.contrast.dark.find(item => item.id === pair.id)
    add(`| ${esc(pair.label)} | \`${pair.fg}\` | \`${pair.bg}\` (${light?.bgHex ?? '—'} / ${dark?.bgHex ?? '—'}) | ${ratio(light?.ratio, light?.threshold)} | ${ratio(dark?.ratio, dark?.threshold)} | ${light?.threshold ?? '—'}${light?.kind === 'disabled' ? '（豁免）' : light?.kind === 'decorative' ? '（装饰）' : ''} |`)
  }
  add('')
  add('## 5. 排版与刻度')
  add('')
